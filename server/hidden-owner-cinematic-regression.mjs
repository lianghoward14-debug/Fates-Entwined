import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const rendering=fs.readFileSync('src/scripts/06-rendering-and-helpers.js','utf8');
const helpers=fs.readFileSync('src/scripts/00-structural-helpers.js','utf8');
const start=rendering.indexOf('function showEffectActivationCinematic(');
const stop=rendering.indexOf("  // Juan's presentation",start);
let viewer=0;
const ctx={window:{},getPerspectivePlayerIndex:()=>viewer};
vm.createContext(ctx);
const visibility=helpers.slice(helpers.indexOf('function isHiddenEffectForViewer('),helpers.indexOf('window.isHiddenEffectForViewer'));
vm.runInContext(visibility+'window.isHiddenEffectForViewer=isHiddenEffectForViewer;'+rendering.slice(start,stop)+'return card;}',ctx);
const source={id:'102',iid:'hidden',owner:0,faceDown:true,_suppressCinematicSubtitle:true};
const shown=await ctx.showEffectActivationCinematic(source,{});
assert.equal(shown.faceDown,false);
assert.equal(shown._suppressCinematicSubtitle,false);
assert.equal(source.faceDown,true,'presentation must never flip the actual card');
viewer=1;
assert.equal(await ctx.showEffectActivationCinematic(source,{}),false);
assert.equal(await ctx.showEffectActivationCinematic(shown,{}),false,'queued owner presentation must recheck its original hidden source');
viewer=0;
assert.equal((await ctx.showEffectActivationCinematic(shown,{})).id,'102');
assert.match(rendering,/if\(!card\?\.faceDown && !options.remote && options.broadcast/,'hidden activation must not broadcast its local cinematic');
console.log('Hidden activation presentation passed: owner cinematic, opponent concealment, queued visibility, unchanged face-down state and no broadcast.');
