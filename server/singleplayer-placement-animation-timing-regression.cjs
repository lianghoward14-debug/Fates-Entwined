const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const core=read('src/scripts/05-gameplay-core.js');
const adapter=read('src/scripts/render-v2/04-match-renderer-adapter.js');
const extract=(s,name,indent='')=>{const a=s.indexOf('function '+name+'(');assert(a>=0);return s.slice(a,s.indexOf('\n'+indent+'}',a)+indent.length+2);};
const timers=[],sounds=[],game={};
const ctx={G:game,window:{FateVfxPrimitives:{cardMove:p=>p}},Date:{now:()=>1000},setTimeout:(fn,ms)=>timers.push({fn,ms}),playSfx:s=>sounds.push(s),document:{querySelector:()=>null},postConsolidationAnimationUntil:()=>0};
vm.createContext(ctx);
vm.runInContext(read('src/scripts/render-v2/13-vfx-recipes.js'),ctx);
const steps=ctx.window.FateVfxRecipes.expand('DESTROY_CARD',{card:{iid:'victim'},iid:'victim',blackRoseBomb:true,bombHoldMs:1000,fromRect:{x:100,y:100,w:80,h:110}});
assert.equal(steps.length,3);assert.equal(steps[0].duration,1000);
assert.deepEqual(steps[0].fromRect,steps[0].toRect);
for(const key of ['rotate','bank','arc','lift','overshoot','launchSquash','landSquash','wobble'])assert.equal(steps[0][key],0,key);
assert.equal(steps[0].scale,1);assert.equal(steps[1].startOffset,1000);assert.equal(steps[2].startOffset,1125);
vm.runInContext(extract(core,'playBlackRoseExplosion'),ctx);
ctx.playBlackRoseExplosion(0,0,0,1000);assert.equal(sounds.length,0);assert.equal(timers[0].ms,1000);
timers.shift().fn();assert.deepEqual(sounds,['blackRoseExplosion']);
ctx.playBlackRoseExplosion(0,0,0,1000);ctx.G={};timers.shift().fn();assert.equal(sounds.length,1,'cancel old-match sound');
vm.runInContext(extract(adapter,'placementFateRevealUntil','  '),ctx);
const card={id:'76',_placementFateReveal:{mode:'set',createdAt:1000}};
assert.equal(ctx.placementFateRevealUntil(card,0),1100);
ctx.G._onlineRoomCode='online';assert.equal(ctx.placementFateRevealUntil(card,0),1340);
ctx.G={};assert.equal(ctx.placementFateRevealUntil({...card,id:'60'},0),1340);
vm.runInContext(extract(read('src/scripts/render-v2/17-action-presentation.js'),'estimateDuration','  '),ctx);
assert.equal(ctx.estimateDuration('DESTROY_CARD',{blackRoseBomb:true,bombHoldMs:1000}),1915);
assert.equal(steps[0].stationaryHold,true);
console.log('Single-player Alpine reveal and one-second stationary landmine timing passed');
