import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'warfront-reset-test-'));
process.env.FATE_FLY_DATA_API_DIR=dir;
process.env.FATE_WARFRONT_MAP_RESET_ID='test-reset';
const file=path.join(dir,'rooms.json');
const original={playerStats:[{uid:'player',challengerElo:999}],warfrontBindings:[{matchId:'old'}],warfrontEvent:{mapCode:'WF-OLD',sequence:1,status:'active',_syncRevision:42,archives:[{mapCode:'archive',zones:[]}],zones:['north-gate','silver-crossing','heartland','sunken-road','crown-reach'].map(id=>({id,a:{uid:'player'},matches:[{id:'old'}]}))}};
fs.writeFileSync(file,JSON.stringify(original));
const {createFlyDataApi}=await import('./fly-data-api.mjs');
const first=createFlyDataApi({});first.flush();
const reset=JSON.parse(fs.readFileSync(file));
assert.notEqual(reset.warfrontEvent.mapCode,'WF-OLD');assert.equal(reset.warfrontEvent._syncRevision,43);
assert(reset.warfrontEvent.zones.every(z=>!z.a&&!z.b&&!z.matches.length));
assert.deepEqual(reset.playerStats,original.playerStats);assert.equal(reset.warfrontEvent.archives.length,1);
assert.deepEqual(JSON.parse(fs.readFileSync(file+'.warfront-reset-test-reset.bak')),original);
createFlyDataApi({}).flush();assert.equal(JSON.parse(fs.readFileSync(file)).warfrontEvent.mapCode,reset.warfrontEvent.mapCode,'restart must not reset again');
console.log('Warfront map reset backs up data, preserves accounts and archives, and runs only once');
