import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {createInitialState} from '../../shared/engine/state.mjs';
import {boardEntries} from '../../shared/engine/selectors.mjs';
import {createEndlessSeaPrior,filterEndlessSeaTiming} from '../../shared/ai/endless-sea-heuristics.mjs';
import {filterAiTargets} from '../../shared/ai/targeting.mjs';
import {preservationProfile} from '../../shared/ai/deck-preservation.mjs';
const require=createRequire(import.meta.url);
const definitions=require('../fate-card-catalog.js').getCardCatalog().cards;
const source=readFileSync(new URL('../../src/scripts/09-challenger-mode.js',import.meta.url),'utf8');
const block=source.slice(source.indexOf("id: 'ai_endless_sea'"));
const ids=vm.runInNewContext(block.match(/ids: (\[[^\]]+\])/)[1]);
assert.equal(ids.length,40);
assert.equal(ids.filter(id=>definitions.find(c=>c.id===id).type==='Supporter').length,24);
assert.ok(!ids.includes('bh09'));
const state=createInitialState({matchId:'sea',seed:'sea',handSize:99,cardDefinitions:definitions,players:[{id:'p0',deckIds:ids},{id:'p1',deckIds:['32']}]});
state.turn=8;state.phase='MAIN';state.pendingPrompt=null;
state.players[0].hand.push(...state.players[0].deck.splice(0));
function place(id,z,r,c){const hand=state.players[0].hand;const card=hand.splice(hand.findIndex(x=>x.id===id),1)[0];state.board[z][r][c]=card;return card;}
const li=place('bh16',0,2,0);
const end={type:'END_TURN',payload:{}};
const activate={type:'ACTIVATE_EFFECT',manualOnly:true,payload:{sourceIid:li.iid}};
const supporter=state.players[0].hand.find(c=>c.id==='33');
const develop={type:'SET_CARD',payload:{cardIid:supporter.iid,destination:{z:1,r:2,c:0}}};
assert.deepEqual(filterAiTargets([activate,develop,end],state,0),[develop,end],'develop before activating');
assert.deepEqual(filterEndlessSeaTiming([activate,end],state,0),[end],'save a small early activation');
const opponent=state.players[1].hand[0];opponent.currentFate=5;state.board[0][0][0]=opponent;
state.moralePressure={morale:[40,200]};
assert.deepEqual(filterEndlessSeaTiming([activate,develop,end],state,0),[activate,develop,end],'urgent zone flip can precede development');
state.moralePressure.morale[0]=200;state.board[0][0][0]=null;
for(const [i,id] of ['53','52','75','74','31'].entries())place(id,1+Math.floor(i/3),2,i%3);
assert.deepEqual(filterEndlessSeaTiming([activate,end],state,0),[activate,end],'spend a mature first activation');
li.counters.effectUses=1;
assert.deepEqual(filterEndlessSeaTiming([activate,end],state,0),[end],'save the last use for a larger field');
place('33',0,2,1);const hidden=place('53',0,2,2);hidden.faceDown=true;
assert.deepEqual(filterEndlessSeaTiming([activate,end],state,0),[activate,end],'count all controlled Eventide cards like the reducer');
const entries=boardEntries(state);
const cards=new Map([...state.players[0].hand,...entries.map(e=>e.card)].map(c=>[c.iid,c]));
const prior=createEndlessSeaPrior(state,0,entries,cards);
assert.ok(prior(develop)>0,'new public list enables supporter development prior');
assert.equal(preservationProfile([...cards.values()]).name,'sea');
state.turn=state.maxTurns-1;
assert.deepEqual(filterEndlessSeaTiming([activate,develop,end],state,0),[activate,develop,end],'do not strand uses on the final owner turn');
state.pendingPrompt={type:'CARD_SELECTION',playerIndex:0};
assert.deepEqual(filterEndlessSeaTiming([activate,end],state,0),[activate,end],'leave prompts alone');
console.log('Endless Seas: public roster, supporter development, patient activations and endgame regressions passed');
