import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createInitialState,legalCommandTemplates,reduceCommand} from '../../shared/engine/index.mjs';
import {completeContinuation} from '../../shared/ai/continuation.mjs';
import {searchWorld} from '../../shared/ai/search.mjs';
const require=createRequire(import.meta.url);
const definitions=require('../fate-card-catalog.js').getCardCatalog().cards;
const state=createInitialState({matchId:'resolved-effects',seed:'effects',handSize:99,cardDefinitions:definitions,players:[{id:'p0',deckIds:['05','09']},{id:'p1',deckIds:['09']}]});
const body=state.players[0].hand.splice(state.players[0].hand.findIndex(c=>c.id==='09'),1)[0];
body.currentFate=20;state.board[0][2][0]=body;
const buff=state.players[0].hand.find(c=>c.id==='05');
const command=legalCommandTemplates(state,0).find(c=>c.type==='SET_CARD' && c.payload.cardIid===buff.iid && c.payload.destination.z===0);
assert(command);
const result=reduceCommand(state,{type:command.type,payload:command.payload,commandId:'start',matchId:state.matchId,expectedRevision:state.revision},{playerId:'p0'});
assert(result.ok);assert(result.state.pendingPrompt);
const snapshot=JSON.stringify(result.state);
const resolved=completeContinuation(result.state,0,{resolutionOnly:true,budget:24,maxSteps:12});
assert(resolved.trace.completed);assert(!resolved.state.pendingPrompt);
assert(resolved.principalVariation.length>0);
assert.equal(JSON.stringify(result.state),snapshot);
const searched=searchWorld(state,0,{nodeBudget:120,width:4,rootCommands:[command]});
assert(searched.principalVariation.some(step=>step.command.type==='ANSWER_PROMPT'));
assert(searched.trace.simulated+searched.trace.rejected<=120);
console.log('Resolved effect search: prompt completion, replay sequence, immutability and budget passed');
