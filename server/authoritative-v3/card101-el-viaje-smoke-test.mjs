import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createInitialState,modifyMorale,cardRule} from '../../shared/engine/index.mjs';
const {cards,byId}=createRequire(import.meta.url)('../fate-card-catalog.js').getCardCatalog();
assert.equal(byId.get('101').fate,1);assert.equal(byId.get('101').cost,4);assert.equal(byId.get('101').type,'Dauntless');
assert(cardRule('101').effectLabels.includes('MORALE_HEAL_FATE_CONVERSION'));
const s=createInitialState({matchId:'printed-jorge',seed:'printed',handSize:9,players:[{id:'p0',deckIds:['101','32']},{id:'p1',deckIds:[]}],cardDefinitions:cards,gameSettings:{healthPressureSeals:true}});
const j=s.players[0].hand.find(c=>c.id==='101'),source=s.players[0].hand.find(c=>c.id==='32');s.players[0].hand=[];s.board[0][2][0]=j;s.board[0][2][1]=source;
modifyMorale({state:s,events:[],ruleEvents:[]},{playerIndex:0,amount:9,sourceIid:source.iid});assert.equal(j.currentFate,4);
console.log('El Viaje: printed 1 Fate / 4 Reinforcement and zone healing conversion passed.');
