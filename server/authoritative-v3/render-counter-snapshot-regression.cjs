const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../../src/scripts/render-v2/01-render-snapshot.js'),'utf8');
const board=Array.from({length:3},()=>Array.from({length:3},()=>[null,null,null]));
const card={iid:'counter-card',id:'121',owner:0,name:'Seventh Magician',type:'Coordinator',rarity:'triangle',aff:'reality',fate:1,currentFate:1,counters:{infernoCounters:3}};
board[0][2][0]=card;
const game={board,players:[{hand:[],deck:[],discard:[]},{hand:[],deck:[],discard:[]}],currentPlayer:0};
const window={getFateGameState:()=>game,performance:{now:()=>0}};
const context={window,performance:window.performance,Date,JSON,WeakSet,Set,Math};
vm.runInNewContext(source,context);
let snapshot=window.FateRenderSnapshot.build();
assert.equal(snapshot.board[0].rows[2].cells[0].card.counters.infernoCounters,3);
assert.equal(snapshot.players[0].hand[0],undefined,'field counters must not spill into the hand');
const priorSignature=snapshot.signature;
card.counters.infernoCounters=4;
snapshot=window.FateRenderSnapshot.build();
assert.equal(snapshot.board[0].rows[2].cells[0].card.counters.infernoCounters,4);
assert.notEqual(snapshot.signature,priorSignature,'counter changes must repaint the board');
console.log('PASS field counter snapshot updates the visible tray');
