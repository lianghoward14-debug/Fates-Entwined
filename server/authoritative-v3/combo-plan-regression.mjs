import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createInitialState} from '../../shared/engine/state.mjs';
import {comboPlan,filterComboPlan} from '../../shared/ai/combo-plan.mjs';
const require=createRequire(import.meta.url);
const definitions=require('../fate-card-catalog.js').getCardCatalog().cards;
const make=ids=>createInitialState({matchId:'planning',seed:'planning',handSize:99,cardDefinitions:definitions,players:[{id:'p0',deckIds:ids},{id:'p1',deckIds:['32']}]});
const s=make(['89','84','bh19','03','32','32','27']);
const hand=s.players[0].hand,id=n=>hand.find(c=>c.id===n).iid;
assert.equal(comboPlan(s,0).phase,'funding');
const discard=id=>({type:'DISCARD_TO_HAND_LIMIT',payload:{discardedIids:[id]}});
assert.deepEqual(filterComboPlan([discard(id('03')),discard(id('32'))],s,0),[discard(id('32'))]);
const end={type:'END_TURN',payload:{}};
const spend={type:'CONSOLIDATE_CARD',payload:{cardIid:id('27'),tributeIids:[id('32')],destination:{z:0,r:2,c:0}}};
assert.deepEqual(filterComboPlan([spend,end],s,0),[end]);
const howard=hand.splice(hand.findIndex(c=>c.id==='03'),1)[0];s.players[0].deck.push(howard);
assert.equal(comboPlan(s,0).phase,'assembling');
s.pendingPrompt={type:'CARD_SELECTION',sourceIid:id('84'),playerIndex:0};
const pick=iid=>({type:'ANSWER_PROMPT',payload:{selectedIid:iid}});
assert.deepEqual(filterComboPlan([pick(howard.iid),pick(id('32'))],s,0),[pick(howard.iid)]);
s.pendingPrompt=null;
const zsofia=hand.splice(hand.findIndex(c=>c.id==='89'),1)[0];s.board[0][2][0]=zsofia;
assert.equal(comboPlan(s,0).anchor.card.iid,zsofia.iid);
s.board[0][2][0]=null;s.players[0].discard.push(zsofia);
assert.equal(comboPlan(s,0).anchor,undefined);
assert(comboPlan(s,0).missing.includes('89'),'removal must invalidate the anchor and replan');
console.log('Combo planning: fuel, discard, search and removal replanning passed');
