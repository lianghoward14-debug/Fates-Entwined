import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createInitialState,reduceCommand,projectStateForPlayer} from '../../shared/engine/index.mjs';
import {legalCommandTemplates} from '../../shared/engine/legal-commands.mjs';
const {cards,byId}=createRequire(import.meta.url)('../fate-card-catalog.js').getCardCatalog();
const star=cards.find(c=>c.rarity==='star');
assert.equal(byId.get('120').name,'The Emerald Eyed Children');
for(const seat of [0,1])for(const hasStar of [false,true]){
 let s=createInitialState({matchId:'120',seed:'120',handSize:99,activePlayer:seat,cardDefinitions:cards,players:[0,1].map(p=>({id:'p'+p,deckIds:p===seat?['120','bh01',hasStar?star.id:'32']:['32']}))});
 const card=s.players[seat].hand.find(c=>c.id==='120');
 const voyager=s.players[seat].hand.splice(s.players[seat].hand.findIndex(c=>c.id==='bh01'),1)[0];
 s.board[0][seat?0:2][1]=voyager;
 s.supportersSetThisTurn[seat]=s.baseSupportersPerTurn;
 const available=()=>legalCommandTemplates(s,seat).some(c=>c.type==='SET_CARD'&&c.payload.cardIid===card.iid);
 assert.equal(available(),false);
 s.supportersSetThisTurn[seat]=0;
 const before=s.supportersSetThisTurn[seat];let serial=0;
 function run(type,payload){const r=reduceCommand(s,{commandId:String(++serial),matchId:s.matchId,expectedRevision:s.revision,type,payload},{playerId:'p'+seat});assert(r.ok,JSON.stringify(r.rejection));s=r.state;return r;}
 const setResult=run('SET_CARD',{cardIid:card.iid,destination:{z:0,r:seat?0:2,c:0}});
 assert.equal(s.supportersSetThisTurn[seat],before+1);
 assert.equal(s.pendingPrompt,null);
 const activation=legalCommandTemplates(s,seat).find(command=>command.type==='ACTIVATE_EFFECT'&&command.payload.sourceIid===card.iid);
 assert(activation);
 run('ACTIVATE_EFFECT',{...activation.payload,userActivated:true});
 assert.equal(s.pendingPrompt?.type,'BOARD_TARGET');
 run('ANSWER_PROMPT',{promptId:s.pendingPrompt.promptId,selectedIid:voyager.iid});
 assert.equal(s.board[0][seat?0:2][1].counters.braveHorizonsCounters,1);
 assert.equal(s.pendingPrompt,null);
 run('ACTIVATE_EFFECT',{...activation.payload,userActivated:true});
 assert.equal(s.pendingPrompt?.type,'BOARD_TARGET');
 run('ANSWER_PROMPT',{promptId:s.pendingPrompt.promptId,cancel:true});
 assert.equal(s.pendingPrompt,null);
 assert.equal(s.board[0][seat?0:2][1].counters.braveHorizonsCounters,1);
 assert(legalCommandTemplates(s,seat).some(command=>command.type==='ACTIVATE_EFFECT'&&command.payload.sourceIid===card.iid));
 run('ACTIVATE_EFFECT',{...activation.payload,userActivated:true});
 run('ANSWER_PROMPT',{promptId:s.pendingPrompt.promptId,selectedIid:voyager.iid});
 assert.equal(s.board[0][seat?0:2][1].counters.braveHorizonsCounters,2);
 assert(!legalCommandTemplates(s,seat).some(command=>command.type==='ACTIVATE_EFFECT'&&command.payload.sourceIid===card.iid));
}
console.log('120: both seats, ordinary set, two manual counter uses, cancellation preserves a use.');
