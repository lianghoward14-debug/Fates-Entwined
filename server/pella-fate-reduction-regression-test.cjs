assert.match(ctx.getBattleOfPellaFateThresholdPanelNote({},0),/Your Fate: 17 \/ Opp: 10/);
ctx.G.board[0][0][0].currentFate=20;
assert.equal(ctx.getLandscapeTotalFate(0),12,'card reduction also lowers total');
ctx.G.fateModifiers.lihua_z0_p0=-30;
assert.equal(ctx.getLandscapeTotalFate(0),0,'reduced zone floors at zero');
ctx.G._phase7ZoneScores=[[6,9],[2,0],[0,0]];
assert.equal(ctx.getLandscapeTotalFate(0),8,'authority scores are respected');
assert.match(ctx.getBattleOfPellaFateThresholdPanelNote({},0),/Your Fate: 8 \/ Opp: 9/);
console.log('Pella Fate reduction regression passed');
