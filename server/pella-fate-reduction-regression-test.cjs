const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const helpers = fs.readFileSync('src/scripts/00-structural-helpers.js','utf8');
const core = fs.readFileSync('src/scripts/05-gameplay-core.js','utf8');
const rendering = fs.readFileSync('src/scripts/06-rendering-and-helpers.js','utf8');
const ctx = {G:{landscapeId:'igb20',board:[[[{owner:0,currentFate:25},{owner:1,currentFate:10}]],[],[]],fateModifiers:{}},window:{},getEffectiveFate:c=>c.currentFate,cardContributesAura:()=>false,isCardEffectSuppressed:()=>false,getLandscapeZoneFateBonus:()=>0};
vm.createContext(ctx);
vm.runInContext(helpers.slice(helpers.indexOf('function getLandscapeTotalFate('),helpers.indexOf('function getFlowingCurrentsLeader(')),ctx);
vm.runInContext(core.slice(core.indexOf('function getBaseZoneScore('),core.indexOf('function fitEndgameWinnerTitle(')),ctx);
vm.runInContext('const BATTLE_OF_PELLA_FATE_DISCARD_THRESHOLDS=[20,35,50];\n'+rendering.slice(rendering.indexOf('function getBattleOfPellaFateThresholdPanelNote('),rendering.indexOf('function getLandscapeFateThresholdClaim(')),ctx);
